#Operators
#Arithmetic Operation

# + = Addition
# - = Subtraction
# * = Multiplication
# / = Division
# ** = Exponential
# // = Floor Division
# % = Modulus

a = 9
b = 7
c = 3

sum = a + b
print("The sum of 9 and 7 is", sum)

difference = a - b
print("The difference between 9 and 7 is", difference)

product = a * b
print("The product of 9 multiplied by 7 is", product)

quotient = a / c
print("If you divide 9 by 3 you will get", quotient)

exponential = b ** c
print("The exponential of 7 and 3 is", exponential)

floordivision = a // b
print("The floor division of 9 and 7 is", floordivision)


modulus = b % c
print("The modulus of 7 and 3 is", modulus)